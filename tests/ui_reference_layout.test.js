const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const assert = (c, m) => { if (!c) throw new Error(m) }

const appWxss = read('miniprogram/app.wxss')
const todayWxml = read('miniprogram/pages/today/today.wxml')
const todayWxss = read('miniprogram/pages/today/today.wxss')
const fixedWxss = read('miniprogram/pages/fixed/fixed.wxss')
const salaryWxss = read('miniprogram/pages/salary/salary.wxss')
const tabWxss = read('miniprogram/custom-tab-bar/index.wxss')

assert(appWxss.includes('background: #faf4ea'), 'Reference cream page background required')
assert(appWxss.includes('border: 2rpx solid #efd6b5'), 'Reference warm card outline required')
assert(appWxss.includes('border-radius: 26rpx'), 'Reference rounded cards required')
assert(todayWxml.includes('今日带薪摸鱼收益'), 'Reference-style earnings label required on home')
assert(todayWxml.includes('今日进度 {{overall.percentage}}%'), 'Reference-style compact progress line required')
assert(todayWxml.includes('class="checklist-card card"'), 'Checklist should be a single outer card like reference')
assert(todayWxml.includes('class="category-panel"'), 'Categories should be nested panels rather than separate floating cards')
assert(todayWxss.includes('.quick-row { display: flex; gap: 10rpx; width: 100%; }'), 'Shortcut rows must fill full card width')
assert(todayWxss.includes('.quick-tool') && todayWxss.includes('flex: 1 1 0;'), 'Shortcut cells must occupy both columns equally')
assert(fixedWxss.includes('background: #faf4ea'), 'Fixed page must use reference palette')
assert(salaryWxss.includes('background: #faf4ea'), 'Salary page must use reference palette')
assert(salaryWxss.includes('grid-template-columns: repeat(3, minmax(0, 1fr))'), 'Fish labels need stable grid')
assert(tabWxss.includes('box-shadow: 0 -8rpx 34rpx'), 'Bottom navigation needs reference floating-card shadow')
assert(fs.existsSync(path.join(root, 'miniprogram/assets/illustrations/reference-hero-strip.png')), 'Runtime hero illustration must be packaged')
assert(!fs.existsSync(path.join(root, 'source/ui_reference/target_ui_reference.png')), 'Private design reference must be omitted from public release')
console.log('PASS ui_reference_layout.test.js')
